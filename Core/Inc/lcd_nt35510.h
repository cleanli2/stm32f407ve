#define LCD_BASE        ((u32)(0x60000000 | 0x0000FFFF))
#else
//使用16位模式时，注意设置时STM32内部会右移一位对齐! 111 1110=0X7E			    
#define LCD_BASE        ((u32)(0x60000000 | 0x0001FFFE))
#endif
#define LCD             ((LCD_TypeDef *) LCD_BASE)


